#!/usr/bin/env bash
# Publish only the tested static files to a deployment branch; never touch main.
set -euo pipefail
root=${KALULU_DEMO_WORKSPACE:-/workspace/kalulu-phone-demo}
repo=$(cd "$(dirname "$0")/.." && pwd)
test -s "$root/logs/demo-test.json"
python3 - "$root/logs/demo-test.json" "$root/web" <<'PY'
import json,pathlib,sys
checks=json.load(open(sys.argv[1]))['checks']
assert not checks.get('failure'),checks
assert checks['originalLessonCompleted']['progression']=='8/8'
assert checks['emulatedPhoneTouch'] and checks['noRuntimeErrors'] and checks['noExternalRequests']
assert pathlib.Path(sys.argv[1]).stat().st_mtime >= max((pathlib.Path(sys.argv[2])/name).stat().st_mtime for name in ['play.pck','play.wasm','play.side.wasm']), 'Build changed since successful browser test'
PY
python3 "$repo/scripts/package_phone_demo.py"
deploy="$root/publish"
if [ ! -d "$deploy" ]; then
  git init -b gh-pages "$deploy"
  git -C "$deploy" remote add origin https://github.com/PJendritza/tmp.git
  if git -C "$deploy" ls-remote --exit-code origin refs/heads/gh-pages >/dev/null; then
    git -C "$deploy" fetch origin gh-pages
    git -C "$deploy" checkout -B gh-pages FETCH_HEAD
  fi
else
  test -d "$deploy/.git"
  test "$(git -C "$deploy" branch --show-current)" = gh-pages
  test -z "$(git -C "$deploy" status --porcelain)" || { echo 'Preserve deployment checkout changes first.' >&2; exit 1; }
  git -C "$deploy" pull --ff-only origin gh-pages
fi
python3 - "$root/web" "$deploy" <<'PY'
import hashlib,json,pathlib,shutil,sys
web,deploy=map(pathlib.Path,sys.argv[1:])
previous=deploy/'FILES.json'
if previous.exists():
    for name in json.loads(previous.read_text()):
        assert pathlib.Path(name).name == name
        target=deploy/name
        if target.is_file(): target.unlink()
elif any(p.name!='.git' for p in deploy.iterdir()):
    raise SystemExit('Existing deployment contents are not generated by this publisher')
files=[]
for source in sorted(web.iterdir()):
    assert source.is_file(),source
    assert source.stat().st_size<100_000_000,source
    shutil.copyfile(source,deploy/source.name)
    files.append(source.name)
(deploy/'FILES.json').write_text(json.dumps(files,indent=2))
with (deploy/'SHA256SUMS').open('w') as output:
    for name in files:
        output.write(hashlib.sha256((deploy/name).read_bytes()).hexdigest()+'  '+name+'\n')
PY
git -C "$deploy" add --all
if ! git -C "$deploy" diff --cached --quiet; then
  git -C "$deploy" commit -m 'Publish tested French Kalulu phone demo'
fi
git -C "$deploy" push -u origin HEAD:refs/heads/gh-pages
echo 'Deployment branch pushed. Pages must be enabled for gh-pages / (root) before the public site can work.'
